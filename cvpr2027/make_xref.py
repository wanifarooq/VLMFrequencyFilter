#!/usr/bin/env python3
"""Turn one document's .aux labels into a static .tex label file for the other.

The main paper and the supplementary cross-reference each other. Overleaf
compiles a single document (and names its aux file output.aux), so the other
document's labels are never available there. This script writes every
\\newlabel of SRC.aux into OUT.tex, which the other document \\input's; both
documents then compile standalone anywhere. Hyperlink anchors are dropped
(the target lives in a different PDF), so these references print as text.
Run by build.sh; usage: python3 make_xref.py SRC.aux OUT.tex
"""
import sys

def args(s, i, n):
    """Parse n brace-delimited arguments starting at s[i]; return (list, end)."""
    out = []
    for _ in range(n):
        while s[i] != "{":
            i += 1
        d, j = 0, i
        while True:
            c = s[j]
            if c == "{": d += 1
            elif c == "}":
                d -= 1
                if d == 0: break
            j += 1
        out.append(s[i + 1:j]); i = j + 1
    return out, i

src, dst = sys.argv[1], sys.argv[2]
lines = ["% Generated by make_xref.py from " + src + " -- do not edit; rerun build.sh.",
         "% Labels of the other document, so this one compiles standalone (e.g. on Overleaf)."]
for raw in open(src, encoding="utf-8", errors="replace"):
    raw = raw.strip()
    if not raw.startswith("\\newlabel{"):
        continue
    (name, val), _ = args(raw, len("\\newlabel"), 2)
    if "@cref" in name:
        lines.append("\\newlabel{%s}{%s}" % (name, val))       # cleveref: type/number/page, no anchor
        continue
    parts, _ = args("{" + val + "}", 0, 1)
    fields, _ = args(parts[0] + "{}{}{}{}{}", 0, 5) if val.count("{") >= 2 else ([val, "", "", "", ""], 0)
    lines.append("\\newlabel{%s}{{%s}{%s}{}{}{}}" % (name, fields[0], fields[1]))  # number, page; no title/anchor
open(dst, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{dst}: {len(lines) - 2} labels")
